@Slf4j
@Service
@RequiredArgsConstructor
public class Import implements Runnable {

    private static final String TABLE_PLACEHOLDER = "{table}";
    private static final DateTimeFormatter dtf = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ssZ").withZone(ZoneId.systemDefault());
    private static final CSVFormat CSV_WITH_FIRST_RECORD_AS_HEADER = CSVFormat.DEFAULT.builder()
            .setHeader()
            .setSkipHeaderRecord(true)
            .get();
    private final static String CREATE_ITEM_TABLE = """
                                                    CREATE TABLE IF NOT EXISTS {table}(
                                                      "pkey" int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                                      "timestamp" TIMESTAMP NOT NULL,
                                                      "id" VARCHAR(32) NOT NULL,
                                                      "status" VARCHAR(16) NOT NULL,
                                                      "dataset_id" VARCHAR(128),
                                                      "label" VARCHAR(1024),
                                                      "provider_id" VARCHAR(256),
                                                      "supplier_id" VARCHAR(128),
                                                      "provider_item_id" VARCHAR(512),
                                                      "sector_fct" VARCHAR(16),
                                                      PRIMARY KEY ("pkey")
                                                    );
                                                    """;

    private final static String CREATE_PERSON_TABLE = """
                                                      CREATE TABLE IF NOT EXISTS {table}(
                                                        "pkey" int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                                        "timestamp" TIMESTAMP NOT NULL,
                                                        "id" VARCHAR(64) NOT NULL,
                                                        "status" VARCHAR(16) NOT NULL,
                                                        "variant_id" VARCHAR(256),
                                                        "preferredName" VARCHAR(1024),
                                                        "type" VARCHAR(32),
                                                        PRIMARY KEY ("pkey")
                                                      );
                                                      """;

    private final static String CREATE_ORGANIZATION_TABLE = """
                                                            CREATE TABLE IF NOT EXISTS {table}(
                                                              "pkey" int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                                              "timestamp" TIMESTAMP NOT NULL,
                                                              "id" VARCHAR(64) NOT NULL,
                                                              "status" VARCHAR(16) NOT NULL,
                                                              "variant_id" VARCHAR(256),
                                                              "preferredName" VARCHAR(1024),
                                                              "type" VARCHAR(32),
                                                              PRIMARY KEY ("pkey")
                                                            );
                                                            """;

    private final static String INSERT_ITEM = """
                                               INSERT INTO {table}("timestamp","id","status","provider_item_id","dataset_id","label","provider_id","sector_fct","supplier_id","pkey")
                                               VALUES (?,?,?,?,?,?,?,?,?,?);
                                               """;

    private final static String INSERT_PERSON = """
                                                 INSERT INTO {table}("timestamp","id","status","variant_id","preferredName","type","pkey")
                                                 VALUES (?,?,?,?,?,?,?);
                                                 """;

    private final static String INSERT_ORGANIZATION = """
                                                       INSERT INTO {table}("timestamp","id","status","variant_id","preferredName","type","pkey")
                                                       VALUES (?,?,?,?,?,?,?);
                                                       """;

    private final Database database;
    private final StatisticsService statisticsService;
    private final ItemService itemService;
    private final PersonService personService;
    private final OrganizationService organizationService;
    private final MaintenanceTables tables;

    @Value("${ddbid.datapath.item}")
    private String dataPathItem;

    @Value("${ddbid.datapath.person}")
    private String dataPathPerson;

    @Value("${ddbid.datapath.organization}")
    private String dataPathOrganization;

    @Override
    public void run() {
        try {
            importToDb();
        } catch (IOException | SQLException ex) {
            throw new IllegalStateException("Could not import comparison files", ex);
        }
    }

    public void importToDb() throws IOException, SQLException {
        Map<Type, Set<File>> inputs = new EnumMap<>(Type.class);
        inputs.put(Type.ITEM, comparisonFiles(dataPathItem));
        inputs.put(Type.PERSON, comparisonFiles(dataPathPerson));
        inputs.put(Type.ORGANIZATION, comparisonFiles(dataPathOrganization));

        List<String> definitions = List.of(
                CREATE_ITEM_TABLE.replace(TABLE_PLACEHOLDER, tables.identifier(Type.ITEM)),
                CREATE_PERSON_TABLE.replace(TABLE_PLACEHOLDER, tables.identifier(Type.PERSON)),
                CREATE_ORGANIZATION_TABLE.replace(TABLE_PLACEHOLDER, tables.identifier(Type.ORGANIZATION)));
        boolean postgres = database.isPostgres();
        if (!postgres) {
            // H2 commits DDL implicitly. Keep it outside the row replacement transaction.
            definitions.forEach(database.getJdbcTemplate()::execute);
        }

        Map<Type, Integer> nextKeys = new EnumMap<>(Type.class);
        boolean committed = false;
        try (Connection connection = database.getConnection()) {
            try {
                if (postgres) {
                    try (Statement statement = connection.createStatement()) {
                        statement.execute(Database.POSTGRES_MAINTENANCE_LOCK_SQL);
                        for (String definition : definitions) {
                            statement.execute(definition);
                        }
                    }
                }
                for (var input : inputs.entrySet()) {
                    if (!input.getValue().isEmpty()) {
                        int lastKey = replaceRows(connection, input.getKey(), input.getValue());
                        nextKeys.put(input.getKey(), Math.incrementExact(lastKey));
                    }
                }
                if (postgres) {
                    restartIdentities(connection, nextKeys);
                }
                connection.commit();
                committed = true;
            } catch (IOException | SQLException | RuntimeException ex) {
                try {
                    connection.rollback();
                } catch (SQLException rollbackFailure) {
                    ex.addSuppressed(rollbackFailure);
                }
                throw ex;
            }
            if (!postgres) {
                restartIdentities(connection, nextKeys);
            }
        } finally {
            if (committed) {
                statisticsService.clearCache();
                itemService.clearTimestampCache();
                personService.clearTimestampCache();
                organizationService.clearTimestampCache();
            }
        }
        statisticsService.ensureDatabaseIndexes();
    }

    private void restartIdentities(Connection connection, Map<Type, Integer> nextKeys) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            for (var entry : nextKeys.entrySet()) {
                statement.execute("ALTER TABLE " + tables.identifier(entry.getKey())
                        + " ALTER COLUMN \"pkey\" RESTART WITH " + entry.getValue());
            }
        }
    }

    private Set<File> comparisonFiles(String dataPath) throws IOException {
        Set<File> files = Helper.getOkCmpFiles(dataPath, Comparator.naturalOrder());
        for (File file : files) {
            String name = file.getName();
            int statusStart = name.lastIndexOf('_') + 1;
            String otherStatus = name.startsWith("MISSING", statusStart) ? "NEW" : "MISSING";
            File paired = new File(file.getParentFile(), name.substring(0, statusStart) + otherStatus + Compare.OUTPUT_FILENAME_EXT);
            if (!files.contains(paired)) {
                throw new IOException("Missing completed comparison file " + paired);
            }
        }
        return files;
    }

    private int replaceRows(Connection connection, Type type, Set<File> files) throws IOException, SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.executeUpdate("DELETE FROM " + tables.identifier(type));
        }
        int rowKey = 0;
        String sql = insertQuery(type).replace(TABLE_PLACEHOLDER, tables.identifier(type));
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            for (File file : files) {
                try (InputStream fileStream = new FileInputStream(file);
                        InputStream gzipStream = new GZIPInputStream(fileStream);
                        var reader = new BufferedReader(new InputStreamReader(gzipStream, StandardCharsets.UTF_8));
                        CSVParser records = CSV_WITH_FIRST_RECORD_AS_HEADER.parse(reader)) {
                    validateHeader(type, records.getHeaderNames());
                    Iterator<CSVRecord> recIt = records.iterator();
                    int count = 0;
                    while (recIt.hasNext()) {
                        final CSVRecord rec = recIt.next();
                        final LocalDateTime localDateTime = LocalDateTime.from(dtf.parse(rec.get("timestamp")));
                        // A complete replacement owns its keys and does not consume the identity sequence.
                        rowKey = Math.incrementExact(rowKey);
                        statement.setTimestamp(1, Timestamp.valueOf(localDateTime));
                        statement.setString(2, rec.get("id"));
                        statement.setString(3, rec.get("status"));
                        switch (type) {
                            case ITEM -> {
                                statement.setString(4, StringUtils.abbreviate(rec.get("provider_item_id"), 512));
                                statement.setString(5, StringUtils.abbreviate(rec.get("dataset_id"), 128));
                                statement.setString(6, StringUtils.abbreviate(rec.get("label"), 1024));
                                statement.setString(7, StringUtils.abbreviate(rec.get("provider_id"), 256));
                                statement.setString(8, StringUtils.abbreviate(rec.get("sector_fct"), 16));
                                statement.setString(9, StringUtils.abbreviate(rec.get("supplier_id"), 128));
                                statement.setInt(10, rowKey);
                            }
                            case PERSON, ORGANIZATION -> {
                                statement.setString(4, StringUtils.abbreviate(rec.get("variant_id"), 256));
                                statement.setString(5, StringUtils.abbreviate(rec.get("preferredName"), 1024));
                                statement.setString(6, StringUtils.abbreviate(rec.get("type"), 32));
                                statement.setInt(7, rowKey);
                            }
                            default -> {
                            }
                        }
                        statement.addBatch();

                        if (++count % 1000 == 0 || !recIt.hasNext()) {
                            statement.executeBatch();
                        }
                    }
                    log.info("Loaded {} {} rows from {}", count, type, file.getName());
                }
            }
        }
        return rowKey;
    }

    private static String insertQuery(Type type) {
        return switch (type) {
            case ITEM -> INSERT_ITEM;
            case PERSON -> INSERT_PERSON;
            case ORGANIZATION -> INSERT_ORGANIZATION;
            default -> throw new IllegalArgumentException("Unsupported type: " + type);
        };
    }

    private static void validateHeader(Type type, Iterable<String> headerNames) {
        final Set<String> headers = new java.util.HashSet<>();
        for (String header : headerNames) {
            headers.add(header);
        }

        final Set<String> expected = switch (type) {
            case ITEM -> Set.of("timestamp", "id", "status", "provider_item_id", "dataset_id", "label", "provider_id", "sector_fct", "supplier_id");
            case PERSON, ORGANIZATION -> Set.of("timestamp", "id", "status", "variant_id", "preferredName", "type");
            default -> throw new IllegalArgumentException("Unsupported type: " + type);
        };
        if (!headers.containsAll(expected)) {
            throw new IllegalArgumentException("CSV header for " + type + " does not contain expected fields " + expected);
        }
    }
}
